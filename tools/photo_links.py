MAP = [(k, n) for k, n in MAP if ok(n)]
tot = drop = 0
for f in sorted(glob.glob(str(ROOT / "story/ch*.js"))):
    L = Path(f).read_text().split("\n"); out = []; seen = set(); started = False
    for l in L:
        s = l.strip()
        if s.startswith("@photo "):
            n = s[7:].split("|")[0].strip()
            if not ok(n): drop += 1; continue
            seen.add(n)
        if s.startswith("@dive"): started = True
        if started and s and not s.startswith(("@", ">", "//")):
            body = re.sub(r"^\[[^\]]*\]\s*", "", s)
            for kw, n in MAP:
                if n in seen: continue
                if re.search(kw, body):
                    if not (out and out[-1].strip().startswith("@photo")):
                        out.append("@photo " + n); tot += 1
                    seen.add(n); break
        out.append(l)
    Path(f).write_text("\n".join(out))
